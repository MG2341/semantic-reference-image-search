from __future__ import annotations

from app.db.sqlite import insert_embedding
from app.domain.models import DEFAULT_SOURCE_INSTITUTION, ImageRecord


def save_image_embedding(
    url: str,
    label: str | None,
    embedding: list[float],
    source_type: str = "unknown",
    source_page_url: str | None = None,
    source_institution: str = DEFAULT_SOURCE_INSTITUTION,
    artist: str | None = None,
    date: str | None = None,
    thumbnail_url: str | None = None,
    credit_line: str | None = None,
    object_name: str | None = None,
    medium: str | None = None,
    dimensions: str | None = None,
    height: str | None = None,
    width: str | None = None,
    department: str | None = None,
    classification: str | None = None,
    culture: str | None = None,
    period: str | None = None,
    dynasty: str | None = None,
    reign: str | None = None,
    country: str | None = None,
    accession_number: str | None = None,
    is_public_domain: bool | None = None,
) -> bool:
    return insert_embedding(
        url=url,
        label=label,
        embedding=embedding,
        source_type=source_type,
        source_page_url=source_page_url,
        source_institution=source_institution,
        artist=artist,
        date=date,
        thumbnail_url=thumbnail_url,
        credit_line=credit_line,
        object_name=object_name,
        medium=medium,
        dimensions=dimensions,
        height=height,
        width=width,
        department=department,
        classification=classification,
        culture=culture,
        period=period,
        dynasty=dynasty,
        reign=reign,
        country=country,
        accession_number=accession_number,
        is_public_domain=is_public_domain,
    )


def save_image_record_embedding(
    record: ImageRecord,
    embedding: list[float],
) -> bool:
    return save_image_embedding(
        url=record.image_url,
        label=record.title or f"Scraped from {record.source_page_url}",
        embedding=embedding,
        source_type=record.source_type,
        source_page_url=record.source_page_url,
        source_institution=record.source_institution,
        artist=record.artist,
        date=record.date,
        thumbnail_url=record.thumbnail_url,
        credit_line=record.credit_line,
        object_name=record.object_name,
        medium=record.medium,
        dimensions=record.dimensions,
        height=record.height,
        width=record.width,
        department=record.department,
        classification=record.classification,
        culture=record.culture,
        period=record.period,
        dynasty=record.dynasty,
        reign=record.reign,
        country=record.country,
        accession_number=record.accession_number,
        is_public_domain=record.is_public_domain,
    )
