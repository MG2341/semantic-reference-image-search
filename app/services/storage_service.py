from __future__ import annotations

from app.db.sqlite import insert_embedding
from app.domain.models import DEFAULT_SOURCE_INSTITUTION


def save_image_embedding(
    url: str,
    label: str | None,
    embedding: list[float],
    source_type: str = "unknown",
    source_page_url: str | None = None,
    source_institution: str = DEFAULT_SOURCE_INSTITUTION,
    artist: str | None = None,
    date: str | None = None,
    thumbnail_url: str | None = None,
    credit_line: str | None = None,
    object_name: str | None = None,
    medium: str | None = None,
    dimensions: str | None = None,
    height: str | None = None,
    width: str | None = None,
    department: str | None = None,
    classification: str | None = None,
    culture: str | None = None,
    period: str | None = None,
    dynasty: str | None = None,
    reign: str | None = None,
    country: str | None = None,
    accession_number: str | None = None,
    is_public_domain: bool | None = None,
) -> bool:
    return insert_embedding(
        url=url,
        label=label,
        embedding=embedding,
        source_type=source_type,
        source_page_url=source_page_url,
        source_institution=source_institution,
        artist=artist,
        date=date,
        thumbnail_url=thumbnail_url,
        credit_line=credit_line,
        object_name=object_name,
        medium=medium,
        dimensions=dimensions,
        height=height,
        width=width,
        department=department,
        classification=classification,
        culture=culture,
        period=period,
        dynasty=dynasty,
        reign=reign,
        country=country,
        accession_number=accession_number,
        is_public_domain=is_public_domain,
    )
